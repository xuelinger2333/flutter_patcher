import 'dart:convert';
import '../core.dart';

/// One `registerWith()` call of Flutter's generated Dart plugin registrant.
typedef PluginRegistration = ({String library, String type});

/// The registrations Flutter's `.dart_tool/flutter_build/dart_plugin_registrant.dart`
/// runs on [platform] (`android` or `ios`). The host ran them at startup for
/// its own plugin copies; a whole-tier module carries separate copies.
List<PluginRegistration> platformRegistrations(
    String registrant, String platform) {
  final imports = {
    for (final m
        in RegExp(r"^import '(package:[^']+)' as (\w+);", multiLine: true)
            .allMatches(registrant))
      m[2]!: m[1]!
  };
  final start = registrant
      .indexOf('if (Platform.${platform == 'ios' ? 'isIOS' : 'isAndroid'}) {');
  require(start >= 0, 'PATCH_SOURCE_INVALID',
      'Unrecognized Dart plugin registrant: no $platform branch');
  final next = RegExp(r'\} else if \(Platform\.')
      .firstMatch(registrant.substring(start + 1));
  final branch = registrant.substring(
      start, next == null ? registrant.length : start + 1 + next.start);
  return [
    for (final m
        in RegExp(r'(\w+)\.(\w+)\.registerWith\(\);').allMatches(branch))
      (
        library: imports[m[1]] ??
            (throw Failure('PATCH_SOURCE_INVALID',
                'Unrecognized Dart plugin registrant import: ${m[1]}')),
        type: m[2]!
      )
  ];
}

/// Package name of a registration's library.
String pluginPackage(PluginRegistration r) =>
    Uri.parse(r.library).pathSegments.first;

/// `__patch_plugins.dart` for a whole-tier module: registers the module's
/// plugin copies the way Flutter's registrant does, then runs the patched main.
String pluginRegistrantSource(
    String package, String target, List<PluginRegistration> registrations) {
  final out = StringBuffer()
    ..writeln(
        '// Generated by flutter_patcher from the Dart plugin registrant.')
    ..writeln(
        'import ${jsonEncode('package:$package/$target').replaceAll(r'$', r'\$')} as app;');
  for (final (i, r) in registrations.indexed) {
    out.writeln('import ${jsonEncode(r.library)} as p$i;');
  }
  out.writeln('Object? patcherMain() {');
  for (final (i, r) in registrations.indexed) {
    out
      ..writeln('  try {')
      ..writeln('    p$i.${r.type}.registerWith();')
      ..writeln('  } catch (err) {')
      ..writeln("    print('`${pluginPackage(r)}` threw an error: \$err.');")
      ..writeln('  }');
  }
  out
    ..writeln('  return (app.main as Object? Function())();')
    ..writeln('}');
  return out.toString();
}
